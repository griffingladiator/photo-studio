<script>

function loadCart() {

    const cart =
        JSON.parse(
            localStorage.getItem("photoCart")
        ) || [];

    const container =
        document.getElementById("cartContent");


    if (cart.length === 0) {

        container.innerHTML = `

            <div class="empty-cart">

                <div class="empty-icon">🛒</div>

                <h2>Your cart is empty</h2>

                <p>
                    Upload a photo and select a printing option
                    to add something to your cart.
                </p>

                <a href="upload.php">
                    Upload Photo
                </a>

            </div>

        `;

        return;
    }


    let total = 0;


    let html = `

        <div class="cart-layout">

            <div class="cart-items">

                <h3>Selected Photos</h3>

    `;


    cart.forEach((item, index) => {

        const itemTotal =
            item.price * item.quantity;

        total += itemTotal;


        html += `

            <div class="cart-item">

                <div class="item-number">
                    ${index + 1}
                </div>

                <div class="item-info">

                    <h4>
                        ${item.product_name}
                    </h4>

                    <p>
                        Price: ₹${item.price.toFixed(2)}
                    </p>

                    <p>
                        Photo ID: ${item.photo_id}
                    </p>

                    <p>
                        Quantity: ${item.quantity}
                    </p>

                </div>


                <div class="item-total">

                    <strong>
                        ₹${itemTotal.toFixed(2)}
                    </strong>

                    <button
                        onclick="removeItem(${index})"
                    >
                        Remove
                    </button>

                </div>

            </div>

        `;

    });


    html += `

            </div>


            <div class="summary">

                <h3>Order Summary</h3>

                <div class="summary-row">

                    <span>Items</span>

                    <span>
                        ${cart.length}
                    </span>

                </div>


                <div class="summary-row">

                    <span>Total</span>

                    <strong>
                        ₹${total.toFixed(2)}
                    </strong>

                </div>


                <a
                    href="checkout.php"
                    class="checkout-btn"
                >
                    Proceed to Checkout →
                </a>


                <a
                    href="upload.php"
                    class="continue-btn"
                >
                    ← Continue Shopping
                </a>

            </div>

        </div>

    `;


    container.innerHTML = html;

}


function removeItem(index) {

    let cart =
        JSON.parse(
            localStorage.getItem("photoCart")
        ) || [];


    cart.splice(index, 1);


    localStorage.setItem(
        "photoCart",
        JSON.stringify(cart)
    );


    loadCart();

}


loadCart();

